export type MessageKey = keyof typeof defaultMessages
export type LanguagePatch = Partial<Record<MessageKey, string>>

declare global {
  interface Window {
    CASECLOSED_LANGUAGE_PATCH?: LanguagePatch
  }
}

let activePatch: LanguagePatch = {}

function isLanguagePatch(value: unknown): value is LanguagePatch {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function readJsonPatch(value: string | null): LanguagePatch {
  if (value === null || value.trim() === '') {
    return {}
  }

  try {
    const parsed = JSON.parse(value) as unknown
    return isLanguagePatch(parsed) ? parsed : {}
  } catch {
    return {}
  }
}

export function loadLanguagePatch(): LanguagePatch {
  const scriptPatch = readJsonPatch(
    document.getElementById('caseclosed-language-patch')?.textContent ?? null,
  )
  const localStoragePatch = readJsonPatch(
    window.localStorage.getItem('caseclosed.languagePatch'),
  )
  return {
    ...scriptPatch,
    ...localStoragePatch,
    ...(window.CASECLOSED_LANGUAGE_PATCH ?? {}),
  }
}

export function applyLanguagePatch(patch: LanguagePatch) {
  activePatch = { ...activePatch, ...patch }
}

export function resetLanguagePatch() {
  activePatch = loadLanguagePatch()
}

export function t(key: MessageKey, values: Record<string, string | number> = {}) {
  const template = activePatch[key] ?? defaultMessages[key]
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template,
  )
}

